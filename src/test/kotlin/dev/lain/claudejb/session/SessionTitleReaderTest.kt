package dev.lain.claudejb.session

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNull
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * Tests [SessionTitleReader.pickTitle]'s pure title-selection logic over raw JSONL lines (no filesystem):
 * ai-title is used, a `/rename` customTitle wins, the last value of each wins, and corrupt/blank input
 * never throws.
 */
class SessionTitleReaderTest {

    @Test
    fun `picks the ai-title`() {
        val lines = listOf(
            """{"type":"queue-operation","sessionId":"s1"}""",
            """{"type":"ai-title","aiTitle":"Plugin reinstalled","sessionId":"s1"}""",
        )
        assertEquals("Plugin reinstalled", SessionTitleReader.pickTitle(lines))
    }

    @Test
    fun `with no title from the binary, the chat is named after what was asked`() {
        // `claude` 2.1.226 CAN generate a title (`saveAiGeneratedTitle` is in the binary) but only does so
        // for an interactive session; the plugin runs it with `--print`, and across 30 real sessions on this
        // machine not one carries an `ai-title` line. So every chat stayed "Chat 3" for its whole life.
        // The binary's own fallback for display is the first meaningful user message
        // (`getFirstMeaningfulUserMessageTextContent`), which is what this mirrors — the first prompt is a
        // good name for a conversation, because it is what you went there to do.
        val lines = listOf(
            """{"type":"queue-operation","sessionId":"s1"}""",
            """{"type":"user","message":{"role":"user","content":[{"type":"text","text":"Arregla el color de los agentes\nsegunda línea"}]}}""",
            """{"type":"user","message":{"role":"user","content":[{"type":"text","text":"y ahora esto otro"}]}}""",
        )
        // The FIRST prompt, first line only.
        assertEquals("Arregla el color de los agentes", SessionTitleReader.pickTitle(lines))
    }

    @Test
    fun `a long prompt is cut on a word, never mid-word`() {
        val long = "Necesito que revises absolutamente todo el sistema de permisos y me digas qué falla"
        val lines = listOf("""{"type":"user","message":{"role":"user","content":[{"type":"text","text":"$long"}]}}""")
        val title = SessionTitleReader.pickTitle(lines)!!
        assertTrue(title.endsWith("…"), "expected an ellipsis, got: $title")
        assertTrue(title.length <= 50, "too long: ${title.length}")
        assertTrue(long.startsWith(title.removeSuffix("…").trim()), "cut mid-word: $title")
    }

    @Test
    fun `the binary's own bookkeeping never becomes the title`() {
        // `user` lines carry the binary's notifications and caveats too. "Caveat: The messages below were
        // generated…" as a tab title is worse than "Chat 3".
        val lines = listOf(
            """{"type":"user","isMeta":true,"message":{"role":"user","content":[{"type":"text","text":"Caveat: The messages below were generated by the user while running local commands."}]}}""",
            """{"type":"user","message":{"role":"user","content":[{"type":"text","text":"<task-notification>algo</task-notification>"}]}}""",
            """{"type":"user","message":{"role":"user","content":[{"type":"text","text":"lo que de verdad pedí"}]}}""",
        )
        assertEquals("lo que de verdad pedí", SessionTitleReader.pickTitle(lines))
    }

    @Test
    fun `a real title from the binary still wins over the prompt`() {
        val lines = listOf(
            """{"type":"user","message":{"role":"user","content":[{"type":"text","text":"lo que pedí"}]}}""",
            """{"type":"ai-title","aiTitle":"Título de verdad","sessionId":"s1"}""",
        )
        assertEquals("Título de verdad", SessionTitleReader.pickTitle(lines))
    }

    @Test
    fun `customTitle wins over ai-title regardless of order`() {
        val lines = listOf(
            """{"type":"ai-title","aiTitle":"Auto generated","sessionId":"s1"}""",
            """{"customTitle":"My rename","sessionId":"s1"}""",
        )
        assertEquals("My rename", SessionTitleReader.pickTitle(lines))
    }

    @Test
    fun `last ai-title wins`() {
        val lines = listOf(
            """{"type":"ai-title","aiTitle":"First","sessionId":"s1"}""",
            """{"type":"ai-title","aiTitle":"Second","sessionId":"s1"}""",
        )
        assertEquals("Second", SessionTitleReader.pickTitle(lines))
    }

    @Test
    fun `skips blank and corrupt lines, never throws`() {
        val lines = listOf(
            "",
            "   ",
            "{not json",
            """{"type":"ai-title","aiTitle":"","sessionId":"s1"}""", // blank ai title ignored
            """{"type":"ai-title","aiTitle":"Good","sessionId":"s1"}""",
        )
        assertEquals("Good", SessionTitleReader.pickTitle(lines))
    }

    @Test
    fun `no title line yields null`() {
        val lines = listOf(
            """{"type":"queue-operation","sessionId":"s1"}""",
            """{"type":"user","content":"hi"}""",
        )
        assertNull(SessionTitleReader.pickTitle(lines))
        assertNull(SessionTitleReader.pickTitle(emptyList()))
    }
}
